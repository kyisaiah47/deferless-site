#!/usr/bin/env node
/* THE REGISTER GATE. It fails closed. No allowlist, no force flag, no known issues file: each
 * of those is a supported way to record a failure and ship past it, which is the behaviour the
 * package this site is about exists to make impossible. A gate on this tree that had one would
 * be arguing with its own subject.
 *
 *   npm run check
 *
 * scripts/deploy.sh runs it before anything is built, so a finding blocks instead of annotates.
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fails = [];
const oks = [];
const fail = (rule, why) => fails.push(`${rule}: ${why}`);
const ok = (rule, note) => oks.push(`${rule}: ${note}`);

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    /* ⛔ BUILD OUTPUT IS NOT WHAT THIS TREE WROTE. `.open-next` and `.wrangler` are generated by
     * opennextjs-cloudflare and by wrangler, both are gitignored, and both carry vendored code
     * with its own punctuation and its own copy of our compiled CSS. */
    if (['node_modules', '.next', '.open-next', '.wrangler', '.git', 'review'].includes(e.name))
      continue;
    /* ⛔ AGENTS.md AND CLAUDE.md ARE WRITTEN BY `next dev` ITSELF, not by this tree. Next 16
     * regenerates them on every run from generate-agent-files.js, and the block it writes
     * carries its own punctuation. They are gitignored for the same reason they are skipped
     * here: they are framework output, like .next. */
    if (e.name === 'AGENTS.md' || e.name === 'CLAUDE.md') continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
};

/* ⛔ THE GATE IS NOT A SUBJECT OF ITS OWN SCAN. It has to spell out what it refuses, so
 * scanning itself makes it fail on its own rule text. Excluded by identity, not by a pattern. */
const SELF = path.join(ROOT, 'scripts', 'check-register.mjs');
const FILES = walk(ROOT).filter((f) => /\.(ts|tsx|mjs|js|css|json|md|svg)$/.test(f) && f !== SELF);
const read = (f) => fs.readFileSync(f, 'utf8');
const rel = (f) => path.relative(ROOT, f);
const src = (f) => read(path.join(ROOT, f));

const ACCENT = '#33c9c4';
const HUE = 191.6;

/* ──────────────────────────────────────────────────────────────────────────────────── 1
 * No dash wider than a hyphen anywhere this tree wrote. The minus sign is the one that gets
 * missed: it is category Sm, so a \p{Pd} test walks straight past it.
 *
 * ⛔ src/lib/demo.ts IS EXCLUDED BY NAME AND FOR ONE REASON. It is the program's own stdout,
 * frozen by scripts/capture.mjs, and `deferless` prints an em dash in its tally line. Rewriting
 * a captured byte would make the page state something the program does not print, which is a
 * worse defect than the character. Rule 6 is what keeps that exclusion honest: it re-runs the
 * program and byte-compares, so nothing can be smuggled through this hole by hand. */
{
  const BAD = [0x2014, 0x2013, 0x2015, 0x2212];
  const hits = [];
  for (const f of FILES) {
    if (rel(f) === 'src/lib/demo.ts') continue;
    if (rel(f).startsWith('vendor/')) continue;
    read(f)
      .split('\n')
      .forEach((line, i) => {
        for (const ch of line) if (BAD.includes(ch.codePointAt(0))) hits.push(`${rel(f)}:${i + 1}`);
      });
  }
  hits.length
    ? fail('1 dashes', `${hits.length} wide dashes: ${[...new Set(hits)].slice(0, 6).join(', ')}`)
    : ok('1 dashes', `${FILES.length} files carry no dash wider than a hyphen`);
}

/* ──────────────────────────────────────────────────────────────────────────────────── 2
 * THE ACCENT PAINTS WHAT THE READER IS DOING, NEVER A VERDICT. It is declared in a fixed set of
 * places, and no exit code ink may take it. This product's whole subject is the difference
 * between pass, fail and could not run, so an accent that also appears on a result makes a
 * fourth ambiguous state. */
{
  const css = src('src/app/globals.css');
  const decl = FILES.filter((f) => new RegExp(ACCENT, 'i').test(read(f))).map(rel).sort();
  const expect = [
    'src/app/globals.css',
    'src/app/icon.svg',
    'src/lib/product.ts',
    'public/favicon.svg',
    'public/mark.svg',
    'README.md',
  ].sort();
  const extra = decl.filter((d) => !expect.includes(d));
  if (extra.length)
    fail('2 accent', `the accent hex appears outside its declared homes: ${extra.join(', ')}`);
  const verdict = css.split('}').filter((b) => /\.exits td\.x\[data-ink|\.t-(pass|fail|quote)/.test(b));
  const stolen = verdict.filter((b) => /var\(--accent/.test(b) || new RegExp(ACCENT, 'i').test(b));
  stolen.length
    ? fail('2 accent', 'an exit code or terminal ink selector takes the accent')
    : ok('2 accent', `declared in ${decl.length} files, and no verdict ink takes it`);
}

/* ──────────────────────────────────────────────────────────────────────────────────── 3
 * THE ACCENT IS THE MIDPOINT OF THE WIDEST EMPTY ARC ON THE ESTATE RING. Re-derived here rather
 * than trusted from the comment that states it, because a comment cannot notice a new product
 * landing on the same hue. */
{
  const reg = path.join(os.homedir(), '.codex/skills/3d-image-gen/product-palette.json');
  if (!fs.existsSync(reg)) {
    fail('3 ring', 'the estate palette registry is not on this machine');
  } else {
    const oklch = (hx) => {
      const h = hx.replace('#', '');
      const [r, g, b] = [0, 2, 4]
        .map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
        .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
      const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
      const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
      const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
      const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
      const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
      return { C: Math.hypot(A, B), H: ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360 };
    };
    const products = JSON.parse(read(reg)).products;
    const hues = Object.entries(products)
      .filter(([, v]) => v.accent)
      .map(([k, v]) => ({ k, ...oklch(v.accent) }))
      .filter((x) => x.C > 0.04 && x.k !== 'deferless');
    const mine = oklch(ACCENT);
    const near = hues
      .map((x) => ({ k: x.k, d: Math.min(Math.abs(x.H - mine.H), 360 - Math.abs(x.H - mine.H)) }))
      .sort((a, b) => a.d - b.d)[0];
    if (Math.abs(mine.H - HUE) > 1)
      fail('3 ring', `the accent hex sits at h ${mine.H.toFixed(1)}, not the h ${HUE} this file declares`);
    else if (near.d < 12)
      fail('3 ring', `the accent is ${near.d.toFixed(1)} degrees from ${near.k}, which is a collision`);
    else
      ok('3 ring', `h ${mine.H.toFixed(1)}, nearest estate accent is ${near.k} at ${near.d.toFixed(1)} degrees`);
  }
}

/* ──────────────────────────────────────────────────────────────────────────────────── 4
 * THE STAT EYEBROW CARD IS BANNED, estate wide and forever. No figure may be the dominant type
 * element on a surface paired with a small tracked all caps label. Nothing on this page is set
 * larger than the headline, so the size jump the ban is about cannot open at all. */
{
  const css = src('src/app/globals.css');
  const headline = Number(/\bh1\s*\{[^}]*font-size:\s*(\d+(?:\.\d+)?)px/.exec(css)?.[1] || 0);
  if (!headline) fail('4 one size', 'h1 declares no font size, so nothing bounds the page');
  else {
    const sizes = [...css.matchAll(/font-size:\s*(\d+(?:\.\d+)?)px/g)].map((m) => Number(m[1]));
    const over = sizes.filter((n) => n > headline);
    over.length
      ? fail('4 one size', `type set larger than the ${headline}px headline: ${over.join(', ')}`)
      : ok('4 one size', `nothing is set larger than the ${headline}px headline`);
  }
}

/* ──────────────────────────────────────────────────────────────────────────────────── 5
 * NO PICTURE TAKES THE WHOLE READING COLUMN. This page draws two kinds of picture, the mark and
 * the shields, and both are drawn at their own intrinsic height in a row of other things. A
 * rule that widened one to the column would be the offence, so assert none exists. */
{
  const css = src('src/app/globals.css');
  const wide = [...css.matchAll(/(img|\.mk|\.badges img|\.studio-credit-mark)[^{]*\{[^}]*width:\s*100%/g)];
  wide.length
    ? fail('5 no full column picture', 'a picture is set to the full column width')
    : ok('5 no full column picture', 'the only pictures are the 22px mark, 20px shields and the 80x20 credit');
}

/* ──────────────────────────────────────────────────────────────────────────────────── 6
 * THE CAPTURED OUTPUT IS THE PROGRAM'S, AND IT IS NOT STALE. This is the rule that earns rule
 * 1's exclusion. It runs the package and byte-compares against the frozen module, so a
 * hand-edited line in demo.ts fails here even though rule 1 does not look at that file.
 *
 * ⛔ A MISSING PACKAGE IS A FAILURE, NOT A SKIP. A renamed or uninstalled dependency that
 * silently stops being checked is indistinguishable from a check that found nothing wrong. That
 * is the package's own promote-gate invariant, applied to its own site. */
{
  const mod = src('src/lib/demo.ts');
  const frozen = JSON.parse(/DEMO_OUTPUT = (".*");/s.exec(mod)?.[1] || '""');
  const ver = JSON.parse(/DEMO_VERSION = (".*?");/.exec(mod)?.[1] || '""');
  const findings = frozen.split('\n').filter((l) => l.startsWith('  ✖ ')).length;
  const tally = /^✖ \d+ violation\(s\)/m.test(frozen);
  const passed = /^✔ \d+ check\(s\) passed/m.test(frozen);

  const CANDIDATES = [
    path.join(ROOT, 'node_modules/deferless/bin/deferless.mjs'),
    path.join(os.homedir(), 'CompoundLabs/deferless/bin/deferless.mjs'),
  ];
  const BIN = CANDIDATES.find((p) => fs.existsSync(p));

  if (!frozen) fail('6 capture', 'src/lib/demo.ts holds no captured output. Run: npm run capture');
  else if (!passed || !tally || findings !== 5)
    fail('6 capture', `the capture lost part of the demo: passed=${passed} tally=${tally} findings=${findings}`);
  else if (!BIN)
    fail('6 capture', 'no deferless on this machine, so the capture cannot be proved fresh. Run: npm i -D deferless');
  else {
    const PKG = path.resolve(BIN, '../..');
    const live = execFileSync('sh', ['-c', `node ${JSON.stringify(BIN)} demo 2>&1`], {
      encoding: 'utf8',
      cwd: PKG,
      maxBuffer: 4 * 1024 * 1024,
    });
    const ESC = String.fromCharCode(27);
    const clean = live
      .replace(new RegExp(ESC + '\\[[0-9;]*[A-Za-z]', 'g'), '')
      .replace(/\r\n/g, '\n')
      .trimEnd()
      .split(PKG + '/')
      .join('')
      .split(os.homedir())
      .join('~');
    const liveVer = JSON.parse(read(path.join(PKG, 'package.json'))).version;
    if (clean !== frozen)
      fail('6 capture', `the frozen output is not what deferless prints today. Run: npm run capture`);
    else if (liveVer !== ver)
      fail('6 capture', `the capture records ${ver} and the package is ${liveVer}. Run: npm run capture`);
    else ok('6 capture', `byte-identical to deferless ${ver} demo, ${findings} findings and the tally`);
  }
}

/* ──────────────────────────────────────────────────────────────────────────────────── 7
 * EVERY CLAIM ABOUT THE PACKAGE CARRIES A URL, A QUOTE AND THE DAY IT WAS READ. A figure with
 * no row in SOURCES does not go on a page. */
{
  const p = src('src/lib/product.ts');
  const rows = [...p.matchAll(/\{\s*\n\s*id: '([^']+)',[\s\S]*?read_at: '([^']+)',\s*\n\s*\}/g)];
  const bad = rows.filter(
    (m) => !/https?:\/\//.test(m[0]) || !/quote:/.test(m[0]) || !/^\d{4}-\d{2}-\d{2}$/.test(m[2]),
  );
  rows.length < 8
    ? fail('7 sources', `only ${rows.length} sources recorded`)
    : bad.length
      ? fail('7 sources', `${bad.length} sources missing a url, a quote or a read date`)
      : ok('7 sources', `${rows.length} sources, each with a verbatim quote, a URL and a read date`);

  /* The page renders the list, so a source row that never reaches a reader is bookkeeping. */
  /SOURCES\.map/.test(src('src/app/page.tsx'))
    ? ok('7 sources', 'the page prints them')
    : fail('7 sources', 'SOURCES is recorded and never rendered');
}

/* ──────────────────────────────────────────────────────────────────────────────────── 8
 * THE COMPOUND LABS CREDIT, ALL FOUR LAYERS. Enforced here because every one of them is
 * invisible when it is wrong: a missing @id still renders, a decorative alt still paints a
 * picture, and a footer that lost the studio's name in live text still passes a grep for it
 * because the alt carries the string. Each layer is asserted on the element that holds it.
 *
 * ⛔ THE MARK IS BYTE-CHECKED, NOT NAME-CHECKED. A red-diamond cube shipped estate wide for
 * four days under this exact filename, so no filename test could see the substitution. */
{
  const layout = src('src/app/layout.tsx');
  const shell = src('src/components/Shell.tsx');
  const notes = [];

  /* 1. Entity. Reference the apex node by @id, never a local Organization declaration. */
  if (!/'@id':\s*'https:\/\/thecompound\.tech\/#organization'/.test(layout))
    notes.push('layer 1: no @id edge to https://thecompound.tech/#organization');

  /* 2. The mark, in an 80x20 box with both dimensions declared and the exact alt. */
  const img = /<img[^>]*studio-credit-mark[\s\S]*?\/>/.exec(shell)?.[0] || '';
  if (!img) notes.push('layer 2: no studio-credit-mark image');
  else {
    if (!/alt="Compound Labs"/.test(img)) notes.push('layer 2: the alt is not exactly "Compound Labs"');
    if (!/width=\{80\}/.test(img) || !/height=\{20\}/.test(img))
      notes.push('layer 2: the mark does not declare both 80 and 20, so the bar reflows on load');
    if (!/src="\/brand\/compound-labs\.svg"/.test(img)) notes.push('layer 2: the mark is not /brand/compound-labs.svg');
  }
  if (!/Built by/.test(shell)) notes.push('layer 2: the words "Built by" are not live text');

  /* The bytes. The one valid Compound Labs logo, compared against the estate's own copy. */
  const mine = path.join(ROOT, 'public/brand/compound-labs.svg');
  const house = path.join(os.homedir(), 'CompoundLabs/compound-ops/brand/compound-labs/logo/compound-labs.svg');
  if (!fs.existsSync(mine)) notes.push('layer 2: public/brand/compound-labs.svg is missing');
  else if (fs.existsSync(house) && read(mine) !== read(house))
    notes.push('layer 2: the vendored mark is not byte-identical to the estate logo');

  /* 3. The copyright line names the studio in live text, beside the picture and never in
   *    place of it. A page can hold a correct lockup and have had the only readable instance
   *    of the name deleted by the same edit that added it. */
  if (!/A Compound Labs product\./.test(shell))
    notes.push('layer 3: no live-text copyright line reading "A Compound Labs product."');

  /* 4. Contact. */
  if (!/hello@thecompound\.tech/.test(shell)) notes.push('layer 4: hello@thecompound.tech is not in the footer');

  /* The retired name, anywhere in the tree. */
  const old = FILES.filter((f) => /hello@kynth\.studio|kynth\.studio\/#organization|A Kynth Studios product/.test(read(f))).map(rel);
  if (old.length) notes.push(`the retired studio identity survives in: ${old.join(', ')}`);

  notes.length
    ? notes.forEach((n) => fail('8 credit', n))
    : ok('8 credit', 'entity @id, the 80x20 mark with its exact alt, the live-text copyright line and the contact');
}

/* ──────────────────────────────────────────────────────────────────────────────────── 9
 * LENIS ALLOWS NESTED SCROLL, AND IT YIELDS TO REDUCED MOTION. Lenis cancels every wheel event
 * it handles, so without the flag the captured terminal block and every code fence on this page
 * are dead: they are the page's only horizontal scrollers and the output in them is column
 * aligned, so they cannot wrap instead. */
{
  const s = src('src/components/SmoothScroll.tsx');
  const notes = [];
  if (!/allowNestedScroll:\s*true/.test(s)) notes.push('Lenis mounts without allowNestedScroll: true');
  if (!/prefers-reduced-motion/.test(s)) notes.push('Lenis mounts regardless of prefers-reduced-motion');
  if (!/lenis\.destroy\(\)/.test(s)) notes.push('the Lenis instance is never destroyed on unmount');
  const scrollers = (src('src/app/globals.css').match(/overflow-x:\s*auto/g) || []).length;
  if (!scrollers) notes.push('nothing on this page scrolls inside itself, so the flag guards nothing');
  notes.length
    ? notes.forEach((n) => fail('9 lenis', n))
    : ok('9 lenis', `allowNestedScroll, reduced motion honoured, ${scrollers} nested scrollers`);
}

/* ─────────────────────────────────────────────────────────────────────────────────── 10
 * THE PRODUCT'S OWN STRINGS LIVE IN ONE FILE. A host, a version or a repo URL typed into a
 * component is a second source of truth that goes stale silently. */
{
  const p = 'src/lib/product.ts';
  const strays = FILES.filter((f) => {
    const r = rel(f);
    if (r === p || r === 'README.md' || r === 'package.json' || r === 'package-lock.json') return false;
    if (r.startsWith('scripts/') || r.startsWith('vendor/')) return false;
    return /deferless\.thecompound\.tech|github\.com\/kyisaiah47\/deferless(?!-)/.test(read(f));
  }).map(rel);
  strays.length
    ? fail('10 one vocabulary', `the host or the repo URL is typed outside ${p}: ${strays.join(', ')}`)
    : ok('10 one vocabulary', `the host, the repo and the version are declared once, in ${p}`);

  const pkgVer = JSON.parse(src('package.json')).devDependencies?.deferless;
  const stated = /version:\s*'([^']+)'/.exec(src(p))?.[1];
  if (pkgVer && stated && !pkgVer.includes(stated))
    fail('10 one vocabulary', `product.ts says ${stated} and package.json pins deferless ${pkgVer}`);
}

/* ─────────────────────────────────────────────────────────────────────────────────── 11
 * NO FILLER. The estate's noise ban, applied to this tree's own copy. Every one of these is a
 * sentence that could be pasted onto a different product unchanged, which is the test. */
{
  const NOISE = [
    'designed to', 'built to help', 'seamlessly', 'effortlessly', 'powerful', 'robust',
    'cutting-edge', 'next-generation', 'game-changing', 'streamline', 'elevate', 'unlock',
    'empower', 'supercharge', 'hassle-free', 'peace of mind', 'at your fingertips',
    'look no further', 'one-stop', 'the ultimate', 'say goodbye to', 'to be honest',
    'to be transparent', 'it is worth mentioning', 'in today',
  ];
  const copy = ['src/lib/product.ts', 'src/app/page.tsx', 'src/components/Shell.tsx'];
  const hits = [];
  for (const f of copy) {
    const body = src(f).toLowerCase();
    for (const n of NOISE) if (body.includes(n)) hits.push(`${f}: ${n}`);
  }
  hits.length
    ? fail('11 no filler', hits.join(', '))
    : ok('11 no filler', `${copy.length} copy files carry none of the ${NOISE.length} banned phrases`);
}

/* ─────────────────────────────────────────────────────────────────────────────────── 12
 * THIS TREE HAS NO WAY TO SHIP PAST A FINDING. The subject of the site would make any of these
 * absurd here, so they are asserted rather than assumed. */
{
  const gate = read(SELF);
  const holes = [];
  /* ⛔ THE TEST IS THAT THE GATE READS NO ARGUMENTS AT ALL, not that it lacks a named flag.
   * The first cut of this clause searched its own source for the string a force flag would be
   * spelled with, and the clause failed on the sentence that forbids it. A gate that takes no
   * argv cannot be given an escape by any spelling, and the assertion cannot self-match. */
  if (/process\.argv/.test(gate)) holes.push('the gate reads command line arguments, so it can be given an escape');
  if (fs.existsSync(path.join(ROOT, 'KNOWN-ISSUES.md'))) holes.push('a known issues file exists');
  if (fs.existsSync(path.join(ROOT, '.check-allow'))) holes.push('an allowlist file exists');
  const deploy = src('scripts/deploy.sh');
  if (!/npm run check/.test(deploy)) holes.push('scripts/deploy.sh does not run this gate');
  if (!/npm run check[\s\S]*opennextjs-cloudflare build/.test(deploy))
    holes.push('scripts/deploy.sh runs the gate after the build rather than in front of it');
  holes.length
    ? holes.forEach((h) => fail('12 no escape', h))
    : ok('12 no escape', 'no force flag, no allowlist, no known issues file, and the gate runs before the build');
}

/* ── report ───────────────────────────────────────────────────────────────────────────── */
for (const o of oks) process.stdout.write(`  ok    ${o}\n`);
if (fails.length) {
  process.stderr.write('\n');
  for (const f of fails) process.stderr.write(`  FAIL  ${f}\n`);
  process.stderr.write(`\n${fails.length} violation(s). Nothing ships.\n`);
  process.exit(1);
}
process.stdout.write(`\n${oks.length} check(s) passed.\n`);
