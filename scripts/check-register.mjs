#!/usr/bin/env node
/* THE REGISTER GATE. Fails closed. No allowlist, no force flag, no known issues file: each of
 * those is a supported way to record a failure and ship past it, which is the exact behaviour
 * the package this site is about exists to make impossible.
 *
 *   npm run check
 */
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fails = [];
const oks = [];
const fail = (rule, why) => fails.push(`${rule}: ${why}`);
const ok = (rule, note) => oks.push(`${rule}: ${note}`);

const walk = (dir, out = []) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    /* ⛔ BUILD OUTPUT IS NOT WHAT THIS TREE WROTE. `.open-next` and `.wrangler` are generated by
     * opennextjs-cloudflare and by wrangler, both are gitignored, and both carry vendored code
     * with its own punctuation and its own copies of our compiled CSS. Scanning them makes the
     * dash rule report Cloudflare's bundler as our em dash and the accent rule report our own
     * compiled stylesheet as the accent escaping its declared homes. `vendor` holds Phosphor's
     * own files, which are theirs. */
    if (['node_modules', '.next', '.open-next', '.wrangler', '.git', 'review', 'vendor'].includes(e.name)) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
};
/* ⛔ THE GATE IS NOT A SUBJECT OF ITS OWN SCAN. It has to spell out every pattern it refuses, so
 * scanning itself makes it fail on its own rule text and there is no way to write it that does
 * not. It is the one file excluded, and it is excluded by identity rather than by a pattern. */
const SELF = path.join(ROOT, 'scripts', 'check-register.mjs');
const FILES = walk(ROOT).filter((f) => /\.(ts|tsx|mjs|js|css|json|md|svg|sh)$/.test(f) && f !== SELF);
const read = (f) => fs.readFileSync(f, 'utf8');
const rel = (f) => path.relative(ROOT, f);
const src = (f) => read(path.join(ROOT, f));

/* dashes. No dash wider than a hyphen anywhere this tree wrote. The minus sign is the one that
 * matters: it is category Sm, so a \p{Pd} test walks straight past it.
 *
 * ⛔ src/lib/demo.ts IS EXEMPT, AND ONLY IT. That file is the package's own stdout, captured
 * byte for byte by scripts/capture.mjs. Rewriting a character of it would make the block stop
 * being what the program prints, which is the one thing that file exists to guarantee. */
{
  const BAD = [0x2014, 0x2013, 0x2015, 0x2212];
  const hits = [];
  for (const f of FILES) {
    if (rel(f) === 'src/lib/demo.ts') continue;
    /* ⛔ AGENTS.md IS NOT WHAT THIS TREE WROTE EITHER. `next dev` writes and re-adds its own
     * block there on every run, punctuation included, and the file says so in its own words.
     * Rewriting a character of it only re-creates the uncommitted change on the next run. */
    if (rel(f) === 'AGENTS.md') continue;
    read(f).split('\n').forEach((line, i) => {
      for (const ch of line) if (BAD.includes(ch.codePointAt(0))) hits.push(`${rel(f)}:${i + 1}`);
    });
  }
  hits.length ? fail('dashes', `${hits.length} wide dashes: ${[...new Set(hits)].slice(0, 6).join(', ')}`)
    : ok('dashes', `${FILES.length} files carry no dash wider than a hyphen`);
}

/* accent. THE ACCENT PAINTS WHAT THE READER IS DOING, NEVER A VERDICT. It is declared in a known
 * set of files, and no exit code selector may take it. This product's whole subject is the
 * difference between pass, fail and could not run, so an accent that also appears on a verdict
 * would make a fourth ambiguous state. */
{
  const css = src('src/app/globals.css');
  const decl = FILES.filter((f) => /#33c9c4/i.test(read(f))).map(rel).sort();
  const expect = ['src/app/globals.css', 'src/app/icon.svg', 'src/lib/product.ts',
    'public/favicon.svg', 'public/mark.svg', 'README.md'].sort();
  const extra = decl.filter((d) => !expect.includes(d));
  if (extra.length) fail('accent', `the accent hex appears outside its declared homes: ${extra.join(', ')}`);
  const verdictRules = css.split('}').filter((b) => /\.st\[data-ink|\.folio-cell\[data-ink|\.term \.t-/.test(b));
  const stolen = verdictRules.filter((b) => /var\(--accent/.test(b) || /#33c9c4/i.test(b));
  stolen.length ? fail('accent', 'an exit code selector takes the accent')
    : ok('accent', `declared in ${decl.length} files, and no exit code selector takes it`);
}

/* ring. The accent is the midpoint of the widest empty arc on the estate ring, and that has to
 * keep being true. Re-derive it rather than trusting the comment in globals.css.
 *
 * ⛔ THREE PRODUCTS POST-DATE THE REGISTRY and are read off their own repos, because a ring that
 * cannot see the newest accents would hand back a slot one of them already holds. */
{
  const reg = path.join(os.homedir(), '.codex/skills/3d-image-gen/product-palette.json');
  if (!fs.existsSync(reg)) { fail('ring', 'the estate palette registry is not on this machine'); }
  else {
    const oklch = (hx) => {
      const h = hx.replace('#', '');
      const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
        .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
      const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
      const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
      const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
      const A = 1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s;
      const B = 0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s;
      return { C: Math.hypot(A, B), H: ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360 };
    };
    const reg_ = JSON.parse(fs.readFileSync(reg, 'utf8')).products;
    const late = { storeready: '#d2ca02', shelfcite: '#1DBDE3', entryline: '#8B7BF0' };
    const hues = [
      ...Object.entries(reg_).filter(([k, v]) => v.accent && k !== 'storeready' && k !== 'deferless')
        .map(([k, v]) => ({ k, ...oklch(v.accent) })),
      ...Object.entries(late).map(([k, v]) => ({ k, ...oklch(v) })),
    ].filter((x) => x.C > 0.04);
    const mine = oklch('#33C9C4');
    const near = hues.map((x) => ({ k: x.k, d: Math.min(Math.abs(x.H - mine.H), 360 - Math.abs(x.H - mine.H)) }))
      .sort((a, b) => a.d - b.d)[0];
    near.d < 12
      ? fail('ring', `the accent is ${near.d.toFixed(1)} degrees from ${near.k}, which is a collision`)
      : ok('ring', `nearest estate accent is ${near.k} at ${near.d.toFixed(1)} degrees`);
  }
}

/* one size. A FIGURE NEVER DOMINATES A SURFACE. The banned register is a numeral set as the
 * largest element with a small tracked all caps label above or below it, and the size jump is
 * the whole of what makes it wrong. Every figure this site prints sits inside a folio line, a
 * table cell, a facts row or a sentence, at the size the register declares for that place, so
 * this measures the jump rather than trusting that nobody wrote one. */
{
  const css = src('src/app/globals.css');
  const headline = Number(/h1\s*\{[^}]*font-size:\s*(\d+)px/.exec(css)?.[1] || 0);
  const over = [...css.matchAll(/font-size:\s*(\d+(?:\.\d+)?)px/g)].map((m) => Number(m[1])).filter((n) => n > headline);
  over.length ? fail('one size', `type set larger than the ${headline}px headline: ${over.join(', ')}`)
    : ok('one size', `nothing is set larger than the ${headline}px headline, so no figure can dominate a surface`);
  /* THE FOLIO FIGURE AND ITS WORDS ARE ONE CELL AT ONE SIZE. The cell declares the size; the <b>
   * carrying the count declares only an ink and a weight, so the two halves cannot drift apart
   * and the jump this rule exists to refuse cannot open at all. The size is REQUIRED to be
   * found: reading a selector that no longer exists returns undefined, and a clause that
   * measured nothing prints a tick. */
  const cell = /\.folio-cell\s*\{[^}]*font-size:\s*(\d+(?:\.\d+)?)px/.exec(css)?.[1];
  const fig = /\.folio-cell b\s*\{[^}]*font-size:\s*(\d+(?:\.\d+)?)px/.exec(css)?.[1];
  const fact = /\.facts-row dd\s*\{[^}]*font-size:\s*(\d+(?:\.\d+)?)px/.exec(css)?.[1];
  const factLab = /\.facts-row dt\s*\{[^}]*font-size:\s*(\d+(?:\.\d+)?)px/.exec(css)?.[1];
  if (!cell) fail('one size', 'the folio cell declares no font size, so nothing bounds the count inside it');
  else if (fig) fail('one size', `the count declares its own ${fig}px, separate from the ${cell}px cell around it`);
  else if (!fact || !factLab) fail('one size', 'a facts row no longer declares both its label and its value size');
  else if (Number(fact) / Number(factLab) >= 1.6) fail('one size', `a facts value is ${(Number(fact) / Number(factLab)).toFixed(2)}x its label, which is the banned jump`);
  else ok('one size', `a folio count and its words are one ${cell}px cell, and a facts value is ${(Number(fact) / Number(factLab)).toFixed(2)}x its label`);
}

/* no full column picture. This site draws three kinds of picture, all of them marks: the product
 * mark, the studio credit mark and the README's own badges. Assert that nothing widens one to
 * the measure. */
{
  const css = src('src/app/globals.css');
  const wide = [...css.matchAll(/(img|\.mk|\.studio-credit-mark|\.badges img)[^{]*\{[^}]*width:\s*100%/g)];
  wide.length ? fail('no full column picture', 'a mark is set to the full column width')
    : ok('no full column picture', 'every picture is a mark, capped at 24px in the masthead, 80px in the credit and 20px tall in a badge');
}

/* no accent bar. ⛔ A border of 2px or more on ONE edge in a visible colour is the accent bar,
 * banned estate wide. An object's identity is its own colour all the way round. A 1px rule on
 * one side is a divider and is not this. */
{
  const css = src('src/app/globals.css');
  const hits = [...css.matchAll(/border-(left|right|top|bottom):\s*(\d+(?:\.\d+)?)px\s+solid\s+([^;]+);/g)]
    .filter((m) => Number(m[2]) >= 2 && !/transparent/.test(m[3]));
  hits.length ? fail('no accent bar', `a one sided border of ${hits[0][2]}px in ${hits[0][3].trim()}`)
    : ok('no accent bar', 'no one sided border is 2px or wider in a visible colour');
}

/* one shape. EVERY GATE CARRIES THE SAME SHAPE. The gate is this console's one control, so a
 * gate whose rows were a different thing would be a second design inside one page and the grid
 * would stop meaning one thing. Every clause names one of the four rails, and nothing else. */
{
  const p = src('src/lib/product.ts');
  const gates = [...p.matchAll(/\n    id: '([a-z-]+)',\n    cmd: 'deferless ([a-z-]+)'/g)].map((m) => m[1]);
  const RAILS = ['filesystem', 'ffmpeg pixels', 'a real browser', 'the shell'];
  const rails = [...p.matchAll(/\n    rail: '([^']+)',/g)].map((m) => m[1]);
  const stray = [...new Set(rails)].filter((r) => !RAILS.includes(r));
  const clauses = [...p.matchAll(/\n    name: '[^']+',\n    reads: '[^']*',\n    refuses:[\s\S]*?\n    rail: '[^']+',/g)];
  const before = fails.length;
  if (gates.length !== 4) fail('one shape', `${gates.length} gates declared, not 4`);
  if (stray.length) fail('one shape', `a clause names a rail the register does not define: ${stray.join(', ')}`);
  if (clauses.length !== rails.length) fail('one shape', `${rails.length} rails but ${clauses.length} complete clauses, so a clause is missing a field`);
  for (const field of ['what', 'incident', 'unit', 'exits', 'usage', 'measured']) {
    const n = [...p.matchAll(new RegExp(`\\n    ${field}:`, 'g'))].length;
    if (n !== 4) fail('one shape', `${n} gates declare ${field}, not 4`);
  }
  if (fails.length === before) ok('one shape', `4 gates, ${clauses.length} clauses, each with what it reads, what makes it refuse and one of the ${RAILS.length} rails`);
}

/* captured. THE BLOCK IS CAPTURED, NEVER TYPED, AND IT IS NOT STALE. A page that retypes a
 * program's output drifts from it the first time the program changes a word, and nothing errors
 * when it does: the block still looks like output. */
{
  const demo = src('src/lib/demo.ts');
  const p = src('src/lib/product.ts');
  const version = /version: '([^']+)'/.exec(p)?.[1];
  const captured = /DEMO_VERSION = "([^"]+)"/.exec(demo)?.[1];
  if (!/GENERATED by scripts\/capture\.mjs/.test(demo)) fail('captured', 'src/lib/demo.ts no longer says it is generated');
  else if (captured !== version) fail('captured', `the capture is of ${captured} and the site states ${version}`);
  else ok('captured', `the block is deferless ${captured}, captured by scripts/capture.mjs`);
  const term = src('src/components/Terminal.tsx');
  /DEMO_OUTPUT\.split\('\\n'\)/.test(term) && !/DEMO_OUTPUT\s*\+/.test(term)
    ? ok('captured', 'the one consumer splits the captured string and writes none of it')
    : fail('captured', 'the terminal component composes output rather than splitting the capture');
}

/* sources. EVERY CLAIM ABOUT THE PACKAGE CARRIES A URL, A VERBATIM QUOTE AND THE DAY IT WAS
 * READ. */
{
  const p = src('src/lib/product.ts');
  const entries = [...p.matchAll(/\{\s*\n\s*id: '([^']+)',[\s\S]*?read_at: '([^']+)',\s*\n\s*\}/g)];
  const bad = entries.filter((m) => !/https?:\/\//.test(m[0]) || !/quote:/.test(m[0]) || !/^\d{4}-\d{2}-\d{2}$/.test(m[2]));
  entries.length < 8 ? fail('sources', `only ${entries.length} sources recorded`)
    : bad.length ? fail('sources', `${bad.length} sources missing a url, a quote or a read date`)
    : ok('sources', `${entries.length} sources, each with a verbatim quote, a URL and a read date`);
}

/* exit codes. THE FOUR ARE DEFINED ONCE and every one carries its own ink. A code printed
 * without its ink is a code a reader cannot tell from any other, and 2 collapsing into the
 * failure ink is the exact confusion the README says matters most. */
{
  const p = src('src/lib/product.ts');
  const block = /export const EXITS = \[([\s\S]*?)\n\] as const;/.exec(p)?.[1] || '';
  const codes = [...block.matchAll(/code: '(\d)'/g)].map((m) => m[1]);
  const inks = [...block.matchAll(/ink: '([a-z]+)'/g)].map((m) => m[1]);
  codes.join() !== ['0', '1', '2', '3'].join() ? fail('exit codes', `EXITS declares ${codes.join(', ') || 'nothing'}, not 0, 1, 2, 3`)
    : new Set(inks).size !== 4 ? fail('exit codes', `the four codes share ${new Set(inks).size} inks, so two read the same`)
    : ok('exit codes', `4 codes, 4 inks: ${codes.map((c, i) => `${c} ${inks[i]}`).join(', ')}`);
  const css = src('src/app/globals.css');
  const painted = ['pass', 'fail', 'caution', 'dim'].filter((i) => new RegExp(`\\.st\\[data-ink='${i}'\\] b`).test(css));
  painted.length === 4 ? ok('exit codes', 'every code has a selector that paints it its own ink')
    : fail('exit codes', `only ${painted.length} of the 4 inks are painted by the code chip`);
}

/* no paid key. NO PAID INFERENCE KEY IS READ ANYWHERE IN THIS TREE. This site calls no model at
 * all, so a reference to one is a reference that should not exist. */
{
  const bad = FILES.filter((f) => /ANTHROPIC_API_KEY|OPENAI_API_KEY|api\.openai\.com|api\.anthropic\.com/.test(read(f)));
  bad.length ? fail('no paid key', `a paid inference key is referenced in ${bad.map(rel).join(', ')}`)
    : ok('no paid key', 'no paid inference key is referenced anywhere in the tree');
}

/* routes. EVERY SITEMAP ROUTE HAS A PAGE, AND llms.txt WRITES ITS ROUTE LIST OFF THE SITEMAP
 * rather than keeping a second list that can drift. */
{
  /* Read the ROUTES array itself rather than every quoted path in the file: a stray match
   * outside it would report a route count that is not the one the sitemap publishes. */
  const arr = /export const ROUTES = \[([^\]]*)\]/.exec(src('src/app/sitemap.ts'))?.[1] || '';
  const routes = [...arr.matchAll(/'(\/[a-z-]*)'/g)].map((m) => m[1]);
  const llms = src('src/app/llms.txt/route.ts');
  const missingPage = routes.filter((r) => !fs.existsSync(path.join(ROOT, 'src/app', r === '/' ? 'page.tsx' : `${r.slice(1)}/page.tsx`)));
  missingPage.length ? fail('routes', `no page behind ${missingPage.join(', ')}`)
    : !/ROUTES\.map/.test(llms) ? fail('routes', 'llms.txt does not write the sitemap route list')
    : ok('routes', `${routes.length} routes, each with a page and each written into /llms.txt off the sitemap`);
}

/* grid lines. THE COLUMN LINES BELONG TO THE GRID, never to a rail's own border, so a short rail
 * cannot cut the line short. */
{
  const css = src('src/app/globals.css');
  const frame = /\.frame::before, \.frame::after \{[^}]*\}/.test(css);
  const railBorder = /\.rail(--r)?\s*\{[^}]*border-(left|right):/.test(css);
  frame && !railBorder ? ok('grid lines', 'the column lines are painted on the frame full height and no rail carries one')
    : fail('grid lines', railBorder ? 'a rail paints a column line on its own border' : 'the frame paints no column lines');
}

/* lenis. IT CARRIES allowNestedScroll. Without it Lenis cancels every wheel event it handles, so
 * no nested overflow box on the page can scroll, and this site is mostly nested scrollers: the
 * captured block, every command, the top rule, the folio and every wide grid. */
{
  const s = src('src/components/SmoothScroll.tsx');
  /allowNestedScroll:\s*true/.test(s) && /prefers-reduced-motion/.test(s)
    ? ok('lenis', 'allowNestedScroll is on and smooth scroll never mounts under prefers-reduced-motion')
    : fail('lenis', 'Lenis is mounted without allowNestedScroll, or without the reduced motion exit');
}

/* studio credit. THE FOUR LAYERS: the publisher node by @id, the Built by mark with its alt, the
 * copyright sentence in live text, and the contact address. */
{
  const layout = src('src/app/layout.tsx');
  const shell = src('src/components/Shell.tsx');
  const misses = [];
  if (!/'@id': 'https:\/\/thecompound\.tech\/#organization'/.test(layout)) misses.push('the publisher @id in the JSON-LD');
  if (!/src="\/brand\/compound-labs\.svg"[\s\S]{0,120}alt="Compound Labs"/.test(shell)) misses.push('the Built by mark with alt="Compound Labs"');
  if (!/A Compound Labs product\./.test(shell)) misses.push('the copyright sentence');
  if (!FILES.some((f) => /hello@thecompound\.tech/.test(read(f)))) misses.push('hello@thecompound.tech');
  if (!fs.existsSync(path.join(ROOT, 'public/brand/compound-labs.svg'))) misses.push('the credit mark file itself');
  misses.length ? fail('studio credit', `missing ${misses.join('; ')}`)
    : ok('studio credit', 'all four layers: the publisher @id, the Built by mark, the copyright sentence and the contact address');
}

/* no noise. NO MARKETING NOISE, and no sentence that could be pasted onto a different product. */
{
  const NOISE = ['designed to', 'built to help', 'seamlessly', 'effortlessly', 'powerful', 'robust',
    'cutting-edge', 'next-generation', 'game-changing', 'streamline', 'elevate', 'unlock', 'empower',
    'supercharge', 'next level', 'in today', 'say goodbye', 'thrilled to', 'excited to', 'one-stop',
    'hassle-free', 'peace of mind', 'at your fingertips', 'look no further', 'the ultimate',
    'to be honest', 'to be transparent', 'it is worth mentioning', 'at the end of the day'];
  const copy = FILES.filter((f) => /^src\//.test(rel(f)) || rel(f) === 'README.md');
  const hits = [];
  for (const f of copy) {
    const body = read(f).toLowerCase();
    for (const n of NOISE) if (body.includes(n)) hits.push(`${rel(f)} carries "${n}"`);
  }
  hits.length ? fail('no noise', hits.slice(0, 6).join('; '))
    : ok('no noise', `${copy.length} files carry none of the ${NOISE.length} banned phrases`);
}

/* family strip. THE APP STRIP IS DERIVED, NEVER HAND EDITED. The family list is written into this
 * repo by compound-ops/roster/build-app-family.mjs off one registry, and every app in a family
 * carries the same list, itself included. A copy this tree authored would diverge the moment the
 * registry changed and nothing would error. */
{
  const f = path.join(ROOT, 'src/lib/app-family.json');
  if (!fs.existsSync(f)) fail('family strip', 'src/lib/app-family.json is missing, so the switch has nothing to open');
  else {
    const fam = JSON.parse(read(f));
    const mine = fam.apps?.some((a) => a.slug === 'deferless-site');
    const strip = src('src/components/AppStrip.tsx');
    !fam.label ? fail('family strip', 'the family copy names no family')
      : !mine ? fail('family strip', 'this app is filtered out of its own family copy, which is what made the lists diverge')
      : !/from '@\/lib\/app-family\.json'/.test(strip) ? fail('family strip', 'the strip does not read the derived copy')
      : ok('family strip', `the ${fam.label} list, read off the derived copy with nothing filtered out`);
  }
}

/* REPORT. Every clause prints, passing or failing, so a rule that quietly stopped running is
 * visible as an absence rather than as a green run. */
for (const o of oks) process.stdout.write(`  ok    ${o}\n`);
for (const f of fails) process.stdout.write(`  FAIL  ${f}\n`);
process.stdout.write(`\n${oks.length} clause(s) held, ${fails.length} refused\n`);
process.exit(fails.length ? 1 : 0);
